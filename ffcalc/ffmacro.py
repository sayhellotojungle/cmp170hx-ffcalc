"""Raw fuse-row readout through the GA100 fuse macro (CMD_READ).

Procedure mirrors kate-land/ga100vfi gpu0-capture: per row -- require
controller IDLE (FUSECTRL state field == 4, low bits 0, FUSEDEBUG == 0),
latch the row into FUSEADDR (verify readback), issue CMD_READ=1 to
FUSECTRL, poll until IDLE again, then read the row from FUSEDATA. CMD_READ
is a command *write* (not a pure MMIO read), so this belongs on an idle
card; the fuse address is restored afterwards.

Works against any BAR0 accessor: pass rd/wr callables (capture.py uses an
mmap; tests use a fake controller). The kernel probe generated by
samples/gen_probe_c.py implements the same sequence in C, emitted verbatim
from PROBE_C here so both sides cannot drift.

The burn path below (sense/arm/program_row) was verified live on a CMP 170HX:
17 records burned, CRC_STATUS stayed 0x55 through a cold boot,
BOOT0=0x170000a1. Writing is destructive -- see docs/BURNING.md. A failed
command parks the controller at FUSECTRL=0xBADFxxxx (state 31) and it stops
answering BAR0 reads: on poison, stop reading, cold-boot, re-sense, do not
retry blindly.
"""
import time

from .optionmap import FF_ROW_MAX, FF_ROW_MIN, IFF_ROW_MAX, IFF_ROW_MIN

FUSECTRL = 0x00820000
FUSEADDR = 0x00820004
FUSEDATA = 0x00820008
FUSEWDATA = 0x0082000C    # record WRITE port (FUSEDATA is read-only)
FUSEDEBUG = 0x00820060    # community name DEBUGCTRL; bit 1 = RWL, which the
                          # community map says selects the RIR macro, so a
                          # non-zero word would send an FF record to rows 0-7
                          # (not reproduced here). The assertion is simply that
                          # the whole word reads 0 before arming.
EN_SW_OVERRIDE = 0x00820040
IFF_RECORD = 0x00820050   # IFF window: start = v & 0x1ff, last = (v >> 16) & 0x1ff
PMC_BOOT_0 = 0x00000000
CRC_STATUS = 0x00820070   # 0x55 = healthy chain CRC
EFP_STATUS = 0x00820078   # expect 1 before arming
DIS_PROGRAM = 0x0082007C  # expect 0; a 1 disables all programming
DSOV_STATUS = 0x00820084  # expect 0 inside the write window
IFF_SW_FUSING = 0x00820088  # write 1 to apply an IFF record for this boot
PLM_FUSE_WDATA = 0x008200F4  # FUSEWDATA privilege; 0xffffffff once unlocked
PRIV_MASK = 0x008200FC    # general privilege mask; holds the SBFE PLM as well
SBFE_SHADOW = 0x00821108  # writable while DSOV == 0
WDATA_WR_SECURE = 0x0082048C  # write 0 -> PLM_FUSE auto-unlocks (0xffffffff)

CMD_READ = 0x1
CMD_PROGRAM = 0x2         # confirmed by experiment: transient 0xE00C0000
CMD_SENSE = 0x3           # re-reads OTP into the shadow, preserves DSOV
IDLE_STATE = 4
POISON_TAG = 0xBADF0000   # controller parks here after a failed command
ROW_COUNT = 512

PER_ROW_TIMEOUT_S = 0.200
TOTAL_TIMEOUT_S = 20.0
PROGRAM_TIMEOUT_S = 10.0


class FuseControllerError(RuntimeError):
    pass


def is_idle(ctrl):
    return ((ctrl >> 16) & 31) == IDLE_STATE and (ctrl & 3) == 0


def capture_rows(rd, wr, first=0, last=ROW_COUNT - 1,
                 sleep=time.sleep, clock=time.monotonic, rows=None):
    """Read physical fuse rows [first..last] -> {row: value32}.

    rd/wr are BAR0 read32/write32 callables. Rows read before an error are
    kept in `rows` (pass a dict to keep a partial capture). Raises
    FuseControllerError on an inaccessible BAR, a busy/failed controller
    or a read timeout; FUSEADDR is restored either way.
    """
    pmc = rd(PMC_BOOT_0)
    if pmc in (0, 0xffffffff) or (pmc & 0xffff0000) == 0xbadf0000:
        raise FuseControllerError(
            "PMC_BOOT_0 reads 0x%08x: BAR0 not accessible / GPU off" % pmc)
    orig_addr = rd(FUSEADDR)
    if rows is None:
        rows = {}
    start = clock()
    try:
        for row in range(first, last + 1):
            if clock() - start > TOTAL_TIMEOUT_S:
                raise FuseControllerError(
                    "total timeout after %d rows" % len(rows))
            ctrl = rd(FUSECTRL)
            if not is_idle(ctrl):
                raise FuseControllerError(
                    "fuse controller %s before row %d (FUSECTRL=0x%08x); "
                    "%s" % ("poisoned" if is_poisoned(ctrl) else "busy",
                            row, ctrl,
                            "stop reads, cold-boot the card"
                            if is_poisoned(ctrl) else
                            "retry on an idle card or after the active op "
                            "finishes"))
            dbg = rd(FUSEDEBUG)
            if dbg != 0:
                raise FuseControllerError(
                    "FUSEDEBUG=0x%08x before row %d; aborting" % (dbg, row))
            wr(FUSEADDR, row)
            if rd(FUSEADDR) != row:
                raise FuseControllerError(
                    "FUSEADDR did not latch row %d" % row)
            wr(FUSECTRL, CMD_READ)
            deadline = clock() + PER_ROW_TIMEOUT_S
            while not is_idle(rd(FUSECTRL)):
                if clock() > deadline:
                    raise FuseControllerError(
                        "CMD_READ timeout at row %d (FUSECTRL=0x%08x)"
                        % (row, rd(FUSECTRL)))
                sleep(0)
            rows[row] = rd(FUSEDATA)
    finally:
        wr(FUSEADDR, orig_addr)
    return rows


def is_poisoned(ctrl):
    """True after a failed command: controller parks at 0xBADFxxxx, state 31,
    and stops answering further BAR0 reads."""
    return (ctrl & 0xFFFF0000) == POISON_TAG


def wait_idle(rd, sleep=time.sleep, clock=time.monotonic, timeout=1.0):
    deadline = clock()
    while clock() - deadline < timeout:
        ctrl = rd(FUSECTRL)
        if is_idle(ctrl):
            return True
        if is_poisoned(ctrl):
            raise FuseControllerError(
                "controller poisoned (FUSECTRL=0x%08x): stop all further "
                "BAR0 reads, cold-boot the card, then SENSE to re-evaluate"
                % ctrl)
        sleep(0)
    return False


def status(rd):
    """Burn-relevant registers, as {name: int}."""
    return {"PMC_BOOT_0": rd(PMC_BOOT_0), "FUSECTRL": rd(FUSECTRL),
            "FUSEADDR": rd(FUSEADDR), "FUSEDATA": rd(FUSEDATA),
            "FUSEDEBUG": rd(FUSEDEBUG), "CRC_STATUS": rd(CRC_STATUS),
            "EFP_STATUS": rd(EFP_STATUS), "DIS_PROGRAM": rd(DIS_PROGRAM),
            "DSOV_STATUS": rd(DSOV_STATUS), "IFF_RECORD": rd(IFF_RECORD),
            "EN_SW_OVERRIDE": rd(EN_SW_OVERRIDE),
            "PLM_FUSE_WDATA": rd(PLM_FUSE_WDATA), "PRIV_MASK": rd(PRIV_MASK),
            "SBFE_SHADOW": rd(SBFE_SHADOW),
            "WDATA_WR_SECURE": rd(WDATA_WR_SECURE)}


def window_problems(rd):
    """[] when the card is inside the burn window; else the reasons why not.

    This is the un-armed half of the picture: nothing here has been written,
    so it is safe to call on any card at any time. The privilege mask is
    included because a glitch that clears DSOV without opening it is the
    near-miss class, not a usable window: DSOV alone is not the test.
    """
    problems = []
    ctrl = rd(FUSECTRL)
    if is_poisoned(ctrl):
        return ["controller poisoned (FUSECTRL=0x%08x): stop, cold boot" % ctrl]
    if not is_idle(ctrl):
        problems.append("FUSECTRL not idle (0x%08x)" % ctrl)
    if rd(FUSEDEBUG) != 0:
        problems.append("FUSEDEBUG/DEBUGCTRL=0x%x (must read 0; bit 1 RWL is "
                        "reported to select the RIR macro instead of the FF one)"
                        % rd(FUSEDEBUG))
    if rd(CRC_STATUS) != 0x55:
        problems.append("CRC_STATUS=0x%x (want 0x55)" % rd(CRC_STATUS))
    if rd(EFP_STATUS) != 1:
        problems.append("EFP_STATUS=%d (want 1)" % rd(EFP_STATUS))
    if rd(DIS_PROGRAM) != 0:
        problems.append("DIS_PROGRAM=%d (want 0: programming is disabled)"
                        % rd(DIS_PROGRAM))
    if rd(DSOV_STATUS) != 0:
        problems.append("DSOV=%d (want 0: inside window)" % rd(DSOV_STATUS))
    if rd(PRIV_MASK) != 0xFFFFFFFF:
        problems.append("PRIV_MASK=0x%08x (want 0xffffffff: near-miss state, "
                        "not a usable window)" % rd(PRIV_MASK))
    return problems


def in_write_window(st):
    """All preconditions for arm/program, from a status() snapshot.

    A snapshot is only as fresh as the rd() behind it, so burntool calls this
    again immediately before it arms; DIS_PROGRAM, the privilege mask and the
    FUSEWDATA PLM are what turn "DSOV happens to read 0" into "a write will
    actually land"."""
    return (is_idle(st["FUSECTRL"]) and not is_poisoned(st["FUSECTRL"])
            and st["FUSEDEBUG"] == 0 and st["CRC_STATUS"] == 0x55
            and st["EFP_STATUS"] == 1 and st["DIS_PROGRAM"] == 0
            and st["DSOV_STATUS"] == 0 and st["PRIV_MASK"] == 0xFFFFFFFF)


def read_row(rd, wr, row, sleep=time.sleep, clock=time.monotonic):
    """One CMD_READ with FUSEADDR restore; blank rows read 0x00000000."""
    if not wait_idle(rd, sleep, clock, PER_ROW_TIMEOUT_S):
        raise FuseControllerError(
            "controller not idle before reading row %d" % row)
    orig = rd(FUSEADDR)
    try:
        wr(FUSEADDR, row)
        if rd(FUSEADDR) != row:
            raise FuseControllerError("FUSEADDR did not latch row %d" % row)
        wr(FUSECTRL, CMD_READ)
        if not wait_idle(rd, sleep, clock, PER_ROW_TIMEOUT_S):
            raise FuseControllerError(
                "CMD_READ timeout at row %d (FUSECTRL=0x%08x)"
                % (row, rd(FUSECTRL)))
        return rd(FUSEDATA)
    finally:
        wr(FUSEADDR, orig)


def sense(rd, wr, sleep=time.sleep, clock=time.monotonic):
    """CMD_SENSE: re-read the OTP array into the shadow. Measured safe
    operation; DSOV must still be 0 afterwards (still inside the window)."""
    if not wait_idle(rd, sleep, clock, PER_ROW_TIMEOUT_S):
        raise FuseControllerError("controller not idle before SENSE")
    wr(FUSECTRL, CMD_SENSE)
    sleep(0.2)
    if not wait_idle(rd, sleep, clock, 2.0):
        raise FuseControllerError(
            "CMD_SENSE did not return to idle (FUSECTRL=0x%08x)"
            % rd(FUSECTRL))
    if rd(DSOV_STATUS) != 0:
        raise FuseControllerError(
            "DSOV=0x%x after SENSE: not inside the write window (no PEX_RST "
            "pulse / boot strap set); do NOT arm or program"
            % rd(DSOV_STATUS))


def armed_problems(rd, wr):
    """[] when a PROGRAM command is allowed right now; else reasons."""
    problems = window_problems(rd)
    if problems and (is_poisoned(rd(FUSECTRL)) or rd(DSOV_STATUS) != 0):
        return problems          # not even in the window; arming is moot
    if rd(SBFE_SHADOW) != 0:
        problems.append("SBFE shadow=%d (want 0: armed)" % rd(SBFE_SHADOW))
    if rd(WDATA_WR_SECURE) != 0:
        problems.append("WDATA_WR_SECURE=%d (want 0: unlocked)"
                        % rd(WDATA_WR_SECURE))
    if rd(PLM_FUSE_WDATA) != 0xFFFFFFFF:
        problems.append("PLM_FUSE_WDATA=0x%08x (want 0xffffffff: the data path "
                        "is still gated, FUSEWDATA writes would be dropped)"
                        % rd(PLM_FUSE_WDATA))
    return problems


def arm(rd, wr):
    """Open the write path: clear the SBFE shadow bit and the WDATA
    secure gate. Raises if the window is not actually open."""
    wr(SBFE_SHADOW, 0)
    wr(WDATA_WR_SECURE, 0)
    problems = armed_problems(rd, wr)
    if problems:
        raise FuseControllerError("not armed: " + "; ".join(problems))


def program_row(rd, wr, row, record, sleep=time.sleep, clock=time.monotonic):
    """Burn one 32-bit record into a blank FF row, with the full assertion
    chain: armed -> row blank -> latch -> WDATA -> PROGRAM -> IDLE ->
    readback. A row that already holds exactly this record is left untouched
    and returned, so re-running an interrupted burn is safe. Raises without
    programming if the row holds anything else."""
    if not FF_ROW_MIN <= row <= FF_ROW_MAX:
        raise FuseControllerError(
            "refusing to program row %d: outside the FF pool %d-%d "
            "(rows 0-%d are factory OTP, rows %d-%d are the IFF window)"
            % (row, FF_ROW_MIN, FF_ROW_MAX, FF_ROW_MIN - 1,
               IFF_ROW_MIN, IFF_ROW_MAX))
    problems = armed_problems(rd, wr)
    if problems:
        raise FuseControllerError("not armed before row %d: %s"
                                  % (row, "; ".join(problems)))
    current = read_row(rd, wr, row, sleep, clock)
    if current == record:
        return current
    if current != 0:
        raise FuseControllerError(
            "row %d is not blank (reads 0x%08x, want 0): refusing to burn"
            % (row, current))
    wr(FUSEADDR, row)
    if rd(FUSEADDR) != row:
        raise FuseControllerError("FUSEADDR did not latch row %d" % row)
    wr(FUSEWDATA, record)
    wr(FUSECTRL, CMD_PROGRAM)
    if not wait_idle(rd, sleep, clock, PROGRAM_TIMEOUT_S):
        raise FuseControllerError(
            "CMD_PROGRAM timeout at row %d (FUSECTRL=0x%08x): treat as "
            "suspect -- stop, cold-boot, re-sense before touching anything"
            % (row, rd(FUSECTRL)))
    got = read_row(rd, wr, row, sleep, clock)
    if got != record:
        raise FuseControllerError(
            "row %d verify mismatch: burned 0x%08x, reads back 0x%08x"
            % (row, record, got))
    return got


def iff_window(rd):
    """(first, last) row of the IFF window, decoded from the card's own word.

    A factory card reads 0x01fb01e8, i.e. 488..507: the window is where the FF
    pool stops, which is why FF_ROW_MAX is IFF_ROW_MIN - 1 and not a guess."""
    v = rd(IFF_RECORD)
    first, last = v & 0x1FF, (v >> 16) & 0x1FF
    if not (0 <= first <= last < ROW_COUNT):
        raise FuseControllerError(
            "IFF_RECORD=0x%08x decodes to rows %d..%d: unusable window"
            % (v, first, last))
    return first, last


def swiff_apply(rd, wr, records, rows=None, sleep=time.sleep,
                clock=time.monotonic):
    """Replay burn records as volatile IFF fuses for this boot (SW-IFF).

    Same 32-bit records program_row would burn, placed instead in the IFF window
    (rows 488-507 on a factory card, read from IFF_RECORD), so a cold boot takes
    them back. `rows`, when given, is {row: value} for the window rows
    (capture_rows covers them); a row that is not blank is skipped so an
    existing record is never overwritten. Returns [(row, record)].

    Needs the burn window exactly like a real burn: this writes, so DSOV == 0,
    FUSEDEBUG == 0, the privilege mask open and EN_SW_OVERRIDE arming must all
    hold. It is therefore not something to attempt on a card that is serving
    traffic, and it never issues CMD_PROGRAM: no cell is burned on this path.

    What the code does per record: arm EN_SW_OVERRIDE, aim IFF_RECORD at one row
    (start and last both that row), latch FUSEADDR to it, write the record to
    FUSEWDATA, then write IFF_SW_FUSING=1 to apply it, and restore FUSEADDR.

    STATUS: never exercised on our hardware. The registers in the sequence have
    all been read off both cards, and the sequence itself is tested against a
    fake controller, but no IFF record has been applied on a real card from this
    code yet -- so what the card does with the record (whether SM count, memory
    size or link training follow it, as the recipe says they do) is the
    recipe's claim, not a measurement, and the first person to run `burntool
    swiff` is the one who verifies it.
    """
    problems = window_problems(rd)
    if problems:
        raise FuseControllerError("cannot SW-IFF: " + "; ".join(problems))
    first, last = iff_window(rd)
    want = list(records)
    if not want:
        return []
    if len(want) > last - first + 1:
        raise FuseControllerError(
            "%d records do not fit the IFF window (rows %d..%d)"
            % (len(want), first, last))
    taken = []
    wr(EN_SW_OVERRIDE, 1)
    if rd(EN_SW_OVERRIDE) != 1:
        raise FuseControllerError(
            "EN_SW_OVERRIDE stayed 0x%x: the override cannot be armed here"
            % rd(EN_SW_OVERRIDE))
    for row in range(first, last + 1):
        if len(taken) == len(want):
            break
        if (rows or {}).get(row, 0) != 0:
            continue
        orig = rd(FUSEADDR)
        try:
            wr(IFF_RECORD, (row << 16) | row)
            wr(FUSEADDR, row)
            if rd(FUSEADDR) != row:
                raise FuseControllerError(
                    "FUSEADDR did not latch IFF row %d" % row)
            wr(FUSEWDATA, want[len(taken)])
            wr(IFF_SW_FUSING, 1)
        finally:
            wr(FUSEADDR, orig)
        taken.append((row, want[len(taken)]))
    if len(taken) != len(want):
        raise FuseControllerError(
            "only %d of %d records found a blank IFF row in %d..%d"
            % (len(taken), len(want), first, last))
    return taken


PROBE_C = """
static inline bool ffprobe_idle(u32 ctrl)
{
\treturn ((ctrl >> 16) & 31) == @IDLE_STATE@ && (ctrl & 3) == 0;
}

static int ffprobe_read_rows(void __iomem *h)
{
\tu32 i, orig, c;
\tint rc = 0;

\torig = readl(h + @FUSEADDR@);
\tfor (i = 0; i < @ROW_COUNT@; i++) {
\t\tunsigned long deadline = jiffies + msecs_to_jiffies(200);

\t\tc = readl(h + @FUSECTRL@);
\t\tif (!ffprobe_idle(c) || readl(h + @FUSEDEBUG@) != 0) {
\t\t\tpr_info("FFPROBE ffrow_error busy_%d %08llx %08x\\n",
\t\t\t\ti, (u64)bar0 + @FUSECTRL@, c);
\t\t\trc = -EBUSY;
\t\t\tbreak;
\t\t}
\t\twritel(i, h + @FUSEADDR@);
\t\twritel(@CMD_READ@, h + @FUSECTRL@);
\t\twhile (!ffprobe_idle(readl(h + @FUSECTRL@))) {
\t\t\tif (time_after(jiffies, deadline)) {
\t\t\t\tpr_info("FFPROBE ffrow_error timeout_%d "
\t\t\t\t\t"00000000 %08x\\n", i,
\t\t\t\t\treadl(h + @FUSECTRL@));
\t\t\t\trc = -ETIMEDOUT;
\t\t\t\tgoto out;
\t\t\t}
\t\t\tudelay(10);
\t\t}
\t\tpr_info("FFPROBE ffrow.%d %08llx %08x\\n", i,
\t\t\t(u64)bar0 + @FUSEDATA@, readl(h + @FUSEDATA@));
\t}
out:
\twritel(orig, h + @FUSEADDR@);
\treturn rc;
}
"""


def probe_c_source():
    """C definitions (idle helper + CMD_READ pass) for the probe module."""
    out = PROBE_C
    for name, value in (("IDLE_STATE", IDLE_STATE), ("FUSECTRL", FUSECTRL),
                        ("FUSEADDR", FUSEADDR), ("FUSEDATA", FUSEDATA),
                        ("FUSEDEBUG", FUSEDEBUG), ("CMD_READ", CMD_READ),
                        ("ROW_COUNT", ROW_COUNT)):
        out = out.replace("@%s@" % name, str(value))
    return out
